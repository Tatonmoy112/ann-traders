// Read-only generation from the isolated PostgreSQL schema. Use CLI generation
// against Supabase for platform schemas when Docker is available.
import pg from 'pg';
import fs from 'node:fs';
const connection = process.env.TEST_DATABASE_URL;
if (!connection) throw new Error('Set TEST_DATABASE_URL to the isolated local database');
if (!['127.0.0.1', 'localhost'].includes(new URL(connection).hostname))
  throw new Error('This script targets local databases only');
const db = new pg.Client({ connectionString: connection });
await db.connect();
const type = (t) =>
  /^(uuid|text|character|timestamp|date|tsvector|name)/.test(t)
    ? 'string'
    : /^(numeric|integer|bigint|smallint|double|real)/.test(t)
      ? 'number'
      : t === 'boolean'
        ? 'boolean'
        : t === 'jsonb' || t === 'json'
          ? 'Json'
          : t === 'void'
            ? 'undefined'
            : t.endsWith('[]')
              ? `${type(t.slice(0, -2))}[]`
              : 'unknown';
let output =
  '// Generated by scripts/introspect-types.mjs from the applied local PostgreSQL schema.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport type Database = {\n';
for (const schema of ['public', 'public_catalog']) {
  output += `${schema}: {\nTables: {\n`;
  const { rows: objects } = await db.query(
    "select c.oid,c.relname,c.relkind from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname=$1 and c.relkind in ('r','v') order by c.relname",
    [schema],
  );
  const render = async (table) => {
    const { rows: columns } = await db.query(
      'select attname,format_type(atttypid,atttypmod) as type,attnotnull,atthasdef,attgenerated from pg_attribute where attrelid=$1 and attnum>0 and not attisdropped order by attnum',
      [table.oid],
    );
    const column = (c) =>
      `${JSON.stringify(c.attname)}: ${type(c.type)}${c.attnotnull ? '' : ' | null'}`;
    let out = `${JSON.stringify(table.relname)}: {Row: {${columns.map(column).join(';')}};`;
    if (table.relkind === 'r') {
      out += `Insert: {${columns
        .filter((c) => !c.attgenerated)
        .map(
          (c) =>
            `${JSON.stringify(c.attname)}${!c.attnotnull || c.atthasdef ? '?' : ''}: ${type(c.type)}${c.attnotnull ? '' : ' | null'}`,
        )
        .join(';')}};`;
      out += `Update: {${columns
        .filter((c) => !c.attgenerated)
        .map(
          (c) => `${JSON.stringify(c.attname)}?: ${type(c.type)}${c.attnotnull ? '' : ' | null'}`,
        )
        .join(';')}};`;
    }
    const { rows: refs } = await db.query(
      "select con.conname,t.relname as target,array(select a.attname::text from unnest(con.conkey) with ordinality k(num,ord) join pg_attribute a on a.attrelid=con.conrelid and a.attnum=k.num order by k.ord) as columns,array(select a.attname::text from unnest(con.confkey) with ordinality k(num,ord) join pg_attribute a on a.attrelid=con.confrelid and a.attnum=k.num order by k.ord) as target_columns from pg_constraint con join pg_class t on t.oid=con.confrelid where con.conrelid=$1 and con.contype='f'",
      [table.oid],
    );
    out += `Relationships: [${refs.map((r) => `{foreignKeyName:${JSON.stringify(r.conname)};columns:${JSON.stringify(r.columns)};isOneToOne:false;referencedRelation:${JSON.stringify(r.target)};referencedColumns:${JSON.stringify(r.target_columns)}}`).join(',')}];};\n`;
    return out;
  };
  for (const table of objects.filter((t) => t.relkind === 'r')) output += await render(table);
  output += '}; Views: {\n';
  for (const view of objects.filter((t) => t.relkind === 'v')) output += await render(view);
  output += '}; Functions: {\n';
  const { rows: funcs } = await db.query(
    "select p.proname,p.proargnames,p.pronargdefaults,format_type(p.prorettype,null) as returns,array(select format_type(t,null) from unnest(p.proargtypes) t) as args from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname=$1 and p.prokind='f' order by proname",
    [schema],
  );
  for (const f of funcs)
    output += `${JSON.stringify(f.proname)}: {Args:{${f.args.map((arg, i) => `${JSON.stringify(f.proargnames?.[i] ?? `arg${i}`)}${i >= f.args.length - f.pronargdefaults ? '?' : ''}:${type(arg)}`).join(';')}};Returns:${type(f.returns)}};\n`;
  output += '}; Enums: {[_ in never]:never}; CompositeTypes: {[_ in never]:never};};\n';
}
output += '};\n';
fs.writeFileSync('packages/database/src/database.types.ts', output);
await db.end();
console.log(
  'Generated schema types from applied PostgreSQL tables, views, relationships and functions.',
);
